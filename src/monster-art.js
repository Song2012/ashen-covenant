// Original 80×96 pixel bestiary. Shape, equipment and anatomy distinguish families.
// The scene caches this once per monster; no art is created inside its frame loop.
const portraitCache=new Map();
export function monsterPortraitDataUrl(monster={}) {
  const key=`${monster.id||monster.family}:${monster.color}:${!!monster.elite}`;
  if(portraitCache.has(key))return portraitCache.get(key);
  const canvas=document.createElement('canvas');canvas.width=80;canvas.height=96;
  drawMonster(canvas.getContext('2d'),monster);
  const url=canvas.toDataURL();portraitCache.set(key,url);return url;
}
