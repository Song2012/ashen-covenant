// scaled with nearest sampling; no external assets, animation, or persistent cache.
export function drawRegion(context,{zoneId='grave',activity='hunt',width=720,height=292}={}){
  const canvas=document.createElement('canvas');canvas.width=360;canvas.height=146;
  const c=canvas.getContext('2d');c.scale(.5,.5);
  const art=kit(c,zoneId==='crypt'?821:zoneId==='furnace'?334:zoneId==='marsh'?119:471);
  if(activity==='boss')throne(art);
  else if(activity==='fish')fishing(art);
  else ({grave,crypt,furnace,marsh}[zoneId]||grave)(art);
  context.save();context.imageSmoothingEnabled=false;context.clearRect(0,0,width,height);context.drawImage(canvas,0,0,width,height);context.restore();
}
